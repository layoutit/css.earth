// Preparation only: source-validated snapshots are never runtime propagators.
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadBodyEpochEphemeris } from './body-epoch-ephemeris.mjs';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const epochJdTt = 2461286.5;
const sources = [
  ['hiiaka', 'haumea', 120136108, 920136108],
  ['menoetius', 'patroclus', 120000617, 920000617],
  ['squannit', 'moshup', null, null],
  ['romulus', 'sylvia', null, null],
  ['sn263-beta', 'asteroid-2001-sn263', null, null],
  ['sn263-gamma', 'asteroid-2001-sn263', null, null],
];
const args = process.argv.slice(2);
if (args.length) throw new Error('No arguments: regenerate all source-state satellites together.');
const records = {};
for (const [bodyId, centerBodyId, target, center] of sources) {
  const bodyRoot = resolve(root, 'src/planets', bodyId);
  const state = await loadBodyEpochEphemeris({ bodyRoot, bodyId, centerBodyId, target, center, epochJdTt });
  // Keep detailed validation receipts in the object source package.
  const provenance = { ...state.provenance };
  delete provenance.validation;
  records[bodyId] = { epochJdTt, ...state, provenance };
}
const output = '// Generated by tools/generate-scene-satellites.mjs from validated object-owned source states.\n' +
  "import type { SceneSatelliteRecord } from '../sceneSatellites.js'\n\n" +
  `export const SCENE_SATELLITE_STATES = ${JSON.stringify(records, null, 2)} as const satisfies Record<string, SceneSatelliteRecord>\n`;
await writeFile(new URL('../src/data/sceneSatelliteStates.data.ts', import.meta.url), output);
console.log(`Prepared ${Object.keys(records).length} source-state satellites at JD${epochJdTt}.`);
