import { createHash, randomUUID } from "node:crypto";
import { rename, rm, writeFile } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";

import { worldDistanceToPolyCss } from "@layoutit/polycss";

import {
  PREPARED_ORBIT_GUIDE_SCHEMA,
  validatePreparedOrbitGuides,
} from "./orbit-guide-contract.mjs";

const PLANET_ID = /^[a-z][a-z0-9-]*$/u;
const BODY_ID = /^[a-z][a-z0-9-]*$/u;
const ASSET_NAME = /^[a-z][a-z0-9@._-]*\.svg$/u;
const HEX_COLOR = /^#[0-9a-f]{6}$/iu;

export async function preparePlanetOrbitGuides({
  planetId,
  bodies,
  source,
  asset,
  presentation,
  hitTest,
  outputModulePath,
}) {
  validatePreparationRequest({
    planetId,
    bodies,
    source,
    asset,
    presentation,
    hitTest,
    outputModulePath,
  });
  const svg = renderOrbitGuideSvg({
    ...asset,
    strokeWidth: asset.strokeWidth,
  });
  const svg2x = renderOrbitGuideSvg({
    ...asset,
    strokeWidth: asset.strokeWidth2x,
  });
  const assetBytes = Buffer.from(svg);
  const asset2xBytes = Buffer.from(svg2x);
  const guides = Object.freeze(bodies.map((body) => {
    const orbitRadius = worldDistanceToPolyCss(body.displayOrbitRadius);
    const scale = orbitRadius / asset.referenceRadius;
    const translation = -asset.center * scale;
    const nodeDeg = body.inclinationDeg === 0 ? 0 : body.nodeDeg;
    return Object.freeze({
      id: body.id,
      displayOrbitRadius: body.displayOrbitRadius,
      orbitRadius,
      inclinationDeg: body.inclinationDeg,
      nodeDeg,
      planeTransform: body.inclinationDeg === 0
        ? ""
        : `rotateY(${-body.inclinationDeg}deg) rotateZ(${-nodeDeg}deg)`,
      leaf: Object.freeze({
        tag: "s",
        style:
          `transform:matrix3d(${scale},0,0,0,0,${scale},0,0,` +
          `0,0,1,0,${translation},${translation},0,1);`,
      }),
    });
  }));
  const prepared = validatePreparedOrbitGuides(Object.freeze({
    schema: PREPARED_ORBIT_GUIDE_SCHEMA,
    planetId,
    model: "one-prepared-vector-circle-leaf-per-orbit-guide",
    source,
    guideCount: guides.length,
    retainedLeafCount: guides.length,
    runtimeGeometryPreparation: false,
    runtimeJavaScriptWritesPerFrame: 0,
    animationCount: 0,
    presentation: Object.freeze({
      baseOpacity: presentation.baseOpacity,
      hoverOpacity: presentation.hoverOpacity,
    }),
    hitTest: Object.freeze({
      model: "event-driven-preprojected-static-conic-nearest-orbit",
      thresholdPixels: hitTest.thresholdPixels,
      projectedOrbitModel: "static-circle-homography-to-screen-conic",
      screenDistanceModel: "implicit-conic-gradient-pixel-distance",
      projectionRefreshEvents: Object.freeze([
        "initial-mount",
        "camera-interaction-end",
        "programmatic-camera-state",
        "resize",
      ]),
      layoutRefreshEvents: Object.freeze(["initial-mount", "resize"]),
      orbitTestsPerCallback: guides.length,
      pointSamplesPerOrbit: 0,
      animationTimeReadsPerCallback: 0,
      trigonometricCallsPerCallback: 0,
      layoutReadsPerHoverCallback: 0,
      layoutReadsPerCameraInteractionEnd: 0,
      touchTapMaxDurationMilliseconds:
        hitTest.touchTapMaxDurationMilliseconds,
      touchTapMaxMovementPixels: hitTest.touchTapMaxMovementPixels,
      runtimeIdleCallbacks: 0,
      runtimeTemporaryObjectsPerOrbit: 0,
    }),
    asset: Object.freeze({
      url: asset.url,
      url2x: asset.url2x,
      width: asset.size,
      height: asset.size,
      width2x: asset.size,
      height2x: asset.size,
      referenceRadius: asset.referenceRadius,
      transparentPaddingPixels: asset.transparentPaddingPixels,
      browserImageType: "image/svg+xml",
      runtimePathGeneration: false,
      bytes: assetBytes.byteLength,
      bytes2x: asset2xBytes.byteLength,
      sha256: digest(assetBytes),
      sha256_2x: digest(asset2xBytes),
      selectedDensityImageCount: 1,
    }),
    guides,
  }));
  const preparedModule =
    "// Generated by a planet-owned preparation command. Do not edit by hand.\n" +
    `export const PREPARED_ORBIT_GUIDES = ${JSON.stringify(prepared)};\n`;
  await Promise.all([
    publishPreparedFile(asset.path, assetBytes),
    publishPreparedFile(asset.path2x, asset2xBytes),
  ]);
  await publishPreparedFile(outputModulePath, preparedModule);
  return prepared;
}

function validatePreparationRequest(request) {
  const { planetId, bodies, source, asset, presentation, hitTest,
    outputModulePath } = request;
  if (!PLANET_ID.test(planetId ?? "") || !Array.isArray(bodies) ||
      bodies.length === 0 || typeof source !== "string" || source.length === 0 ||
      typeof outputModulePath !== "string" || outputModulePath.length === 0) {
    throw new TypeError("Orbit-guide preparation request is incompatible.");
  }
  const ids = new Set();
  for (const body of bodies) {
    if (!body || !BODY_ID.test(body.id ?? "") || ids.has(body.id) ||
        !positive(body.displayOrbitRadius) ||
        !finite(body.inclinationDeg) || body.inclinationDeg < 0 ||
        body.inclinationDeg > 180 || !finite(body.nodeDeg) ||
        body.nodeDeg < 0 || body.nodeDeg >= 360) {
      throw new TypeError("Orbit-guide body source is incompatible.");
    }
    ids.add(body.id);
  }
  const prefix = `/scenes/${planetId}/`;
  if (!asset || !validAssetUrl(asset.url, prefix) ||
      !validAssetUrl(asset.url2x, prefix) || asset.url === asset.url2x ||
      typeof asset.path !== "string" || typeof asset.path2x !== "string" ||
      asset.path.length === 0 || asset.path2x.length === 0 ||
      asset.path === asset.path2x ||
      !Number.isSafeInteger(asset.size) || asset.size <= 2 ||
      !positive(asset.center) || asset.center >= asset.size ||
      !positive(asset.referenceRadius) ||
      asset.center - asset.referenceRadius !==
        asset.transparentPaddingPixels ||
      asset.size - asset.center - asset.referenceRadius !==
        asset.transparentPaddingPixels ||
      !positive(asset.strokeWidth) || !positive(asset.strokeWidth2x) ||
      !HEX_COLOR.test(asset.strokeColor ?? "") ||
      !Number.isSafeInteger(asset.transparentPaddingPixels) ||
      asset.transparentPaddingPixels < 0 ||
      !presentation || !finite(presentation.baseOpacity) ||
      !finite(presentation.hoverOpacity) ||
      presentation.baseOpacity < 0 || presentation.baseOpacity > 1 ||
      presentation.hoverOpacity < presentation.baseOpacity ||
      presentation.hoverOpacity > 1 ||
      !hitTest || !positive(hitTest.thresholdPixels) ||
      !positive(hitTest.touchTapMaxDurationMilliseconds) ||
      !positive(hitTest.touchTapMaxMovementPixels)) {
    throw new TypeError("Orbit-guide preparation settings are incompatible.");
  }
}

function validAssetUrl(value, prefix) {
  return typeof value === "string" && value.startsWith(prefix) &&
    ASSET_NAME.test(value.slice(prefix.length));
}

function renderOrbitGuideSvg({
  size,
  center,
  referenceRadius,
  strokeColor,
  strokeWidth,
}) {
  return `<svg xmlns="http://www.w3.org/2000/svg" ` +
    `width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">` +
    `<circle cx="${center}" cy="${center}" r="${referenceRadius}" ` +
    `fill="none" stroke="${strokeColor}" stroke-width="${strokeWidth}"/>` +
    `</svg>\n`;
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function publishPreparedFile(path, bytes) {
  const temporaryPath = resolve(
    dirname(path),
    `.${basename(path)}.${randomUUID()}.tmp`,
  );
  try {
    await writeFile(temporaryPath, bytes, { flag: "wx" });
    await rename(temporaryPath, path);
  } finally {
    await rm(temporaryPath, { force: true });
  }
}

function positive(value) {
  return finite(value) && value > 0;
}

function finite(value) {
  return typeof value === "number" && Number.isFinite(value);
}
