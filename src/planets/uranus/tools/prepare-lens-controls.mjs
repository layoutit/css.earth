import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const descriptions = {
  normal: "Hubble visible color",
  methane: "Hubble at 727 nm",
  "near-infrared": "Hubble at 845 nm",
};

export function serializePreparedLensControls(lenses) {
  const controls = lenses.controls.map(lens => ({ id: lens.id, label: lens.label, thumbnailUrl: lens.thumbnailUrl,
    description: descriptions[lens.id], title: lens.falseColor ? `${lens.label}: ${lens.qualification}` : lens.qualification }));
  if (!controls.some(control => control.id === lenses.defaultLens) || controls.some(control =>
    Object.values(control).some(value => typeof value !== "string" || value.length === 0))) {
    throw new TypeError("Uranus lens controls require complete prepared UI content.");
  }
  return `// Generated by tools/prepare-lens-controls.mjs during scene preparation.\nexport const PREPARED_LENS_CONTROLS = Object.freeze(${JSON.stringify({ defaultLens: lenses.defaultLens, controls })});\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const { PREPARED_URANUS_LENSES } = await import("../runtime/preparedLenses.mjs");
  await writeFile(new URL("../site/preparedLensControls.mjs", import.meta.url), serializePreparedLensControls(PREPARED_URANUS_LENSES));
}
