#!/usr/bin/env node
// Mercury's catalogue sky: the HYG stars as retained point sources in the
// ICRF cube frame the photographic sky is sampled in, selected and banded by
// apparent magnitude here, never in the browser. The source is the vendored
// `catalogs/stars-hyg` (data/catalogs, CC-BY-SA-4.0); its bytes are hashed
// into the prepared module so the output is reproducible from the checked-in
// input. Reads the prepared starfield plan for the shared projection and the
// photographic separation gains the coexistence record cites.

import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { readVendoredCatalog } from "../../../platform/catalog-package.mjs";
import { prepareCatalogSky } from "../../../platform/catalog-sky-preparation.mjs";
import { PREPARED_MERCURY_STARFIELD } from "../runtime/preparedStarfield.mjs";

// Bands by apparent magnitude. The faintest edge is the point population's
// limit: the photometric pin at the shared 60-degree projection sits near
// 5.6, and 5.0 keeps the retained element count near 1,600, which measured
// free of frame cost in Chrome (2,800 cost a third of the frame budget).
// Everything fainter stays with the photograph.
export const MERCURY_CATALOG_SKY_BAND_EDGES = Object.freeze([1, 2, 3, 4, 4.5, 5]);

const { catalog, provenance } = await readVendoredCatalog("catalogs/stars-hyg");
const separation = PREPARED_MERCURY_STARFIELD.photographicSeparation;
const plan = prepareCatalogSky({
  catalog,
  provenance,
  projection: PREPARED_MERCURY_STARFIELD.projection,
  bandEdges: MERCURY_CATALOG_SKY_BAND_EDGES,
  photographicCoexistence: Object.freeze({
    photograph: PREPARED_MERCURY_STARFIELD.source,
    photographicSeparationModel: separation.model,
    photographicDiffuseGain: separation.standardDiffuseGain,
    photographicDetailGain: separation.standardDetailGain,
    photographicRegistrationResidualsDegrees:
      PREPARED_MERCURY_STARFIELD.astrometricRegistration.panorama.frameCorrection.residualsDegrees,
    photographicPixelsPerDegree: PREPARED_MERCURY_STARFIELD.sourceMapSize[0] / 360,
  }),
});
await writeFile(
  resolve(import.meta.dirname, "../runtime/preparedCatalogSky.mjs"),
  "// Generated by src/planets/mercury/tools/prepare-catalog-sky.mjs from the\n" +
    "// vendored HYG catalogue (data/catalogs/stars-hyg, CC-BY-SA-4.0). Do not edit.\n" +
    `export const PREPARED_MERCURY_CATALOG_SKY = Object.freeze(${JSON.stringify(plan)});\n`,
);
console.log(`Prepared ${plan.count} Mercury catalogue stars in ${plan.bands.length} bands ` +
  `(${plan.bands.map((band) => `<=${band.edgeMagnitude}: ${band.count}`).join(", ")}), ` +
  `${plan.named.length} named.`);
