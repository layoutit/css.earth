#!/usr/bin/env node
// Marker tiles for the dwarf planets in Mercury's planetary system. The
// shell's navigation atlas carries Pluto; Ceres, Eris, Haumea and Makemake
// have no navigation entry and no photographic tile, so this prepares one
// small strip of flat-colour discs for them at the two prepared densities.
// The discs are synthetic (a soft-edged disc of each body's published
// visible colour, not imagery) and are labelled as such in the prepared
// module; they are billboards at a fixed screen size, never geometry.

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import sharp from "sharp";

const projectRoot = resolve(import.meta.dirname, "../../../..");
const outputDirectory = resolve(projectRoot, "public/scenes/mercury");
const moduleTarget = resolve(projectRoot, "src/planets/mercury/runtime/preparedSystemMarkers.mjs");

// Visible colours from the literature: Ceres is a dark neutral grey
// (geometric albedo 0.09, Dawn); Eris is nearly white (methane frost, albedo
// 0.96); Haumea is neutral white-grey (crystalline water ice); Makemake is
// reddish-brown (tholins). Sizes follow the shell's marker sizing (Pluto is
// 6 px there); the strip order is fixed by this table.
const TILES = Object.freeze([
  { id: "ceres", color: [110, 106, 102], size: 5 },
  { id: "eris", color: [232, 230, 226], size: 6 },
  { id: "haumea", color: [217, 216, 212], size: 5 },
  { id: "makemake", color: [185, 138, 106], size: 5 },
]);
const TILE_PIXELS = 16;

await mkdir(outputDirectory, { recursive: true });
const files = {};
for (const density of [1, 2]) {
  const tile = TILE_PIXELS * density;
  const width = tile * TILES.length;
  const raw = Buffer.alloc(width * tile * 4);
  TILES.forEach(({ color }, index) => {
    const centre = (tile - 1) / 2;
    const radius = tile / 2 - 0.5 * density;
    for (let y = 0; y < tile; y += 1) {
      for (let x = 0; x < tile; x += 1) {
        const distance = Math.hypot(x - centre, y - centre);
        // A one-pixel soft edge; a slight limb darkening so the disc reads
        // as a body rather than a dot.
        const coverage = Math.max(0, Math.min(1, radius - distance + 0.5));
        const shade = 1 - 0.25 * Math.min(1, distance / radius) ** 2;
        const offset = ((y * width) + index * tile + x) * 4;
        raw[offset] = Math.round(color[0] * shade);
        raw[offset + 1] = Math.round(color[1] * shade);
        raw[offset + 2] = Math.round(color[2] * shade);
        raw[offset + 3] = Math.round(255 * coverage);
      }
    }
  });
  const fileName = density === 1
    ? "mercury-system-markers.webp"
    : "mercury-system-markers@2x.webp";
  const target = resolve(outputDirectory, fileName);
  await sharp(raw, { raw: { width, height: tile, channels: 4 } })
    .webp({ lossless: true })
    .toFile(target);
  const bytes = await readFile(target);
  files[density] = Object.freeze({
    url: `/scenes/mercury/${fileName}`,
    width,
    height: tile,
    tilePixels: tile,
    bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  });
}

const prepared = Object.freeze({
  schema: "cssmercury-prepared-system-markers@1",
  model: "synthetic-flat-colour-discs",
  provenance: "Flat-colour discs from published visible colours; not imagery. " +
    "Pluto uses the shell's navigation atlas tile instead.",
  count: TILES.length,
  tiles: Object.freeze(Object.fromEntries(TILES.map(({ id, size }, index) =>
    [id, Object.freeze({ index, count: TILES.length, size })]))),
  density1: files[1],
  density2: files[2],
});
await writeFile(
  moduleTarget,
  `// Generated by src/planets/mercury/tools/prepare-system-markers.mjs. Do not edit.\n` +
    `export const PREPARED_MERCURY_SYSTEM_MARKERS = Object.freeze(${JSON.stringify(prepared)});\n`,
);
console.log(`Prepared ${TILES.length} Mercury system marker tiles -> ${files[1].url}, ${files[2].url}`);
