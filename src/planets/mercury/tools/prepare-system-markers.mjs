#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { prepareSolarSystemMarkerStrip } from "../../../../tools/objects/solar-system-markers.mjs";
import solarSystemSource from "../source/presentation/solar-system.json" with { type: "json" };
import { MERCURY_PUBLIC_ROOT } from "./preparation-paths.mjs";
import { validateMercurySourceGroup } from "./source-manifest.mjs";

await validateMercurySourceGroup("system-markers");
const { plan, assets } = await prepareSolarSystemMarkerStrip(solarSystemSource.markerStrip);
await mkdir(MERCURY_PUBLIC_ROOT, { recursive: true });
for (const asset of assets) await writeFile(resolve(MERCURY_PUBLIC_ROOT, asset.url.split("/").at(-1)), asset.bytes);
await writeFile(new URL("../runtime/preparedSystemMarkers.mjs", import.meta.url),
  "// Generated by src/planets/mercury/tools/prepare-system-markers.mjs. Do not edit.\n" +
  `export const PREPARED_MERCURY_SYSTEM_MARKERS = Object.freeze(${JSON.stringify(plan)});\n`);
console.log(`Prepared ${plan.count} Mercury system marker tiles.`);
