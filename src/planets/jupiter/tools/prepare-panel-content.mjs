import { writeFile } from "node:fs/promises";

import editorial from "../../../../data/planets/jupiter.json" with { type: "json" };
import moonCatalog from "../source/moons/jupiter-moons.json" with { type: "json" };
import { PREPARED_JUPITER_MOONS } from "../runtime/preparedMoons.mjs";
import { PREPARED_JUPITER_RINGS } from "../runtime/preparedRings.mjs";

const output = new URL("../site/preparedPanel.mjs", import.meta.url);
const size = sectionText("Size and Distance");
const orbit = sectionText("Orbit and Rotation");
const moons = sectionText("Moons");
const formation = sectionText("Formation");
const structure = sectionText("Structure");
const atmosphere = sectionText("Atmosphere");
const rings = sectionText("Rings");

const distance = capture(size, /\(778 million kilometers\)/u, "778 million km");
const radius = Number(capture(size, /\((69,911) kilometers\)/u).replace(",", ""));
const year = capture(orbit, /in about (12 Earth years)/u);
const day = `${capture(orbit, /takes (9\.9) hours/u)} hours`;
assertIncludes(moons, "Io, Europa, Ganymede, and Callisto");
assertIncludes(editorial.introduction, "largest planet in our solar system");
assertIncludes(formation, "fifth planet from the Sun");
assertIncludes(structure, "mostly hydrogen and helium");
assertIncludes(atmosphere, "colorful stripes and spots");
assertIncludes(rings, "small, dark particles");
assertIncludes(rings, "difficult to see except when backlit by the Sun");
if (moonCatalog.counts.confirmed !== PREPARED_JUPITER_MOONS.counts.moonCount) {
  throw new Error("Jupiter panel moon count does not match the prepared scene.");
}

export const PREPARED_JUPITER_PANEL = deepFreeze({
  schema: "cssearth-prepared-panel@1",
  planetId: "jupiter",
  introduction: "The fifth planet from the Sun, Jupiter is the solar system's largest planet: a gas giant wrapped in colorful clouds and enormous storms.",
  facts: [
    { id: "distance-from-sun", label: "Distance from Sun", value: distance },
    { id: "diameter", label: "Diameter", value: `${(radius * 2).toLocaleString("en-US")} km` },
    { id: "orbital-period", label: "Orbital period", value: year },
    { id: "rotation-period", label: "Rotation period", value: day },
    { id: "axial-tilt", label: "Axial tilt", value: `${capture(orbit, /tilted[^.]+by just (3) degrees/u)}\u00b0` },
    {
      id: "moon-count",
      label: "Moons",
      value: `${moonCatalog.counts.confirmed}`,
    },
    { id: "ring-system", label: "Rings", value: "Present" },
  ],
  moreFacts: [
    {
      id: "wind-speed",
      label: "Wind",
      value: `${capture(atmosphere, /\((539) kilometers per hour\)/u)} km/h`,
    },
    {
      id: "great-red-spot-depth",
      label: "Great Red Spot depth",
      value: `${capture(atmosphere, /depth of about 300 miles \((500) kilometers\)/u)} km`,
    },
  ],
  sources: {
    editorial: {
      sourceId: editorial.sourceId,
      sourceUrl: editorial.sourceUrl,
      modified: editorial.modified,
      retrievedAt: editorial.retrievedAt,
      credit: editorial.credit,
    },
    renderedMoons: {
      count: PREPARED_JUPITER_MOONS.counts.moonCount,
      detailedCount: PREPARED_JUPITER_MOONS.counts.detailedMoonCount,
      minorCount: PREPARED_JUPITER_MOONS.counts.minorMoonCount,
      retrievedAt: moonCatalog.retrievedAt,
      sources: moonCatalog.sources,
      physicalParameters: PREPARED_JUPITER_MOONS.sourceAuthority.physicalParameters,
      meanElements: PREPARED_JUPITER_MOONS.sourceAuthority.meanElements,
    },
    rings: {
      parts: PREPARED_JUPITER_RINGS.system.parts,
      components: PREPARED_JUPITER_RINGS.system.components.map((component) =>
        component.name),
      statistics: PREPARED_JUPITER_RINGS.sourceAuthority.statistics,
      observation: PREPARED_JUPITER_RINGS.sourceAuthority.mainHaloObservation,
      qualification: PREPARED_JUPITER_RINGS.presentation.qualification,
    },
  },
});

await writeFile(
  output,
  `// Generated by tools/prepare-panel-content.mjs from declared local sources.\nexport const PREPARED_JUPITER_PANEL = Object.freeze(${JSON.stringify(PREPARED_JUPITER_PANEL)});\n`,
);
console.log(`Prepared Jupiter panel content -> ${output.pathname}`);

function sectionText(heading) {
  const section = editorial.sections.find((entry) => entry.heading === heading);
  if (!section) throw new Error(`Jupiter editorial snapshot is missing ${heading}.`);
  return section.paragraphs.join(" ");
}

function capture(text, pattern, replacement) {
  const match = text.match(pattern);
  if (!match) throw new Error(`Jupiter editorial fact no longer matches ${pattern}.`);
  return replacement ?? match[1];
}

function assertIncludes(text, value) {
  if (!text.includes(value)) throw new Error(`Jupiter editorial fact is missing ${value}.`);
}

function deepFreeze(value) {
  for (const child of Object.values(value)) {
    if (child && typeof child === "object") deepFreeze(child);
  }
  return Object.freeze(value);
}
