#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { validatePlanetInformationSnapshot } from "../../../../tools/planet-information-sources.mjs";
import { validateSunSourceGroup } from "./source-manifest.mjs";

await validateSunSourceGroup("panel");
const snapshot = JSON.parse(await readFile(resolve(
  import.meta.dirname,
  "../source/editorial/sun.json",
), "utf8"));
validatePlanetInformationSnapshot(snapshot);
for (const required of [
  "4.5 billion-year-old yellow dwarf star",
  "center of our solar system",
  "life as we know it",
]) {
  if (!snapshot.introduction.includes(required)) {
    throw new Error(`NASA Sun introduction no longer supports prepared excerpt: ${required}.`);
  }
}

const prepared = Object.freeze({
  schema: "csssun-prepared-panel@1",
  sourceId: snapshot.sourceId,
  sourceUrl: snapshot.sourceUrl,
  modified: snapshot.modified,
  retrievedAt: snapshot.retrievedAt,
  introduction: "At the center of our solar system, the Sun is a 4.5-billion-year-old yellow dwarf star. Its light and heat make life on Earth possible.",
  facts: Object.freeze([
    Object.freeze({ label: "Radius", value: "700,000 km" }),
    Object.freeze({ label: "Distance from Earth", value: "150 million km" }),
    Object.freeze({ label: "Equatorial rotation", value: "25 Earth days" }),
    Object.freeze({ label: "Galactic orbit", value: "230 million years" }),
  ]),
  moreFacts: Object.freeze([
    Object.freeze({ label: "Age", value: "4.5 billion years" }),
    Object.freeze({ label: "Solar-system mass", value: "99.8%" }),
    Object.freeze({ label: "Photosphere", value: "5,500 °C" }),
    Object.freeze({ label: "Core", value: "15 million °C" }),
    Object.freeze({ label: "Magnetic cycle", value: "about 11 years" }),
  ]),
});

const sourceText = JSON.stringify(snapshot);
for (const required of [
  "700,000 kilometers",
  "150 million kilometers",
  "25 Earth days",
  "230 million years",
  "99.8%",
  "5,500 degrees Celsius",
  "15 million °C",
  "Approximately every 11 years",
]) {
  if (!sourceText.includes(required)) {
    throw new Error(`NASA Sun editorial no longer supports prepared fact: ${required}.`);
  }
}

await writeFile(
  new URL("../site/preparedPanel.mjs", import.meta.url),
  "// Generated by tools/prepare-panel-content.mjs.\n" +
    `export const PREPARED_SUN_PANEL = Object.freeze(${JSON.stringify(prepared)});\n`,
);
