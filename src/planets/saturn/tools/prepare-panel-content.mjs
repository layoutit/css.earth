import { writeFile } from "node:fs/promises";

import editorial from "../../../../data/planets/saturn.json" with { type: "json" };
import moonCatalog from "../source/moons/saturn-moons.json" with { type: "json" };
import { validateSaturnSourceGroup } from "./source-manifest.mjs";

await validateSaturnSourceGroup("panel");

const output = new URL("../site/preparedPanel.mjs", import.meta.url);
const size = sectionText("Size and Distance");
const orbit = sectionText("Orbit and Rotation");
const moons = sectionText("Moons");
const rings = sectionText("Rings");
const atmosphere = sectionText("Atmosphere");
const structure = sectionText("Structure");

assertIncludes(editorial.introduction, "sixth planet from the Sun");
assertIncludes(editorial.introduction, "second-largest planet");
assertIncludes(structure, "giant gas planet");
assertIncludes(rings, "ice and rock");

const editorialMoonCount = Number(capture(
  moons,
  /As of March 2025, Saturn had (274) confirmed moons/u,
));
const renderedMoonCount = moonCatalog.counts.confirmed;

export const PREPARED_SATURN_PANEL = deepFreeze({
  schema: "cssearth-prepared-panel@1",
  planetId: "saturn",
  introduction: "The sixth planet from the Sun, Saturn is a vast gas giant surrounded by spectacular rings made of countless pieces of ice and rock.",
  facts: [
    { label: "Distance", value: `${capture(size, /\((1\.4 billion) kilometers\)/u)} km` },
    { label: "Diameter", value: `${capture(size, /\((120,500) kilometers\)/u)} km` },
    { label: "Year", value: `${capture(orbit, /about (29\.4) Earth years/u)} Earth yrs` },
    { label: "Day", value: `${capture(orbit, /takes only (10\.7) hours/u)} hours` },
  ],
  moreFacts: [
    { label: "Light time", value: `${capture(size, /takes sunlight (80) minutes/u)} min` },
    { label: "Tilt", value: `${capture(orbit, /tilted by (26\.73) degrees/u)}°` },
    {
      label: "Moons",
      value: String(editorialMoonCount),
      title: `NASA Science editorial snapshot: ${editorialMoonCount} confirmed moons as of March 2025. The rendered JPL catalog contains ${renderedMoonCount} objects retrieved ${moonCatalog.retrievedAt}.`,
    },
    { label: "Ring extent", value: `${capture(rings, /\((282,000) kilometers\)/u)} km`, title: "Maximum extent from Saturn" },
    { label: "Ring height", value: `${capture(rings, /\((10) meters\)/u)} m`, title: "Typical height of the main rings" },
    { label: "Wind", value: `${capture(atmosphere, /\((500) meters per second\)/u)} m/s`, title: "Upper-atmosphere equatorial wind speed" },
  ],
  moonCountPolicy: {
    editorial: editorialMoonCount,
    editorialAsOf: "2025-03",
    rendered: renderedMoonCount,
    renderedRetrievedAt: moonCatalog.retrievedAt,
    rule: "Display the NASA editorial count with its date. Render the newer JPL catalog count without rewriting NASA's dated prose.",
  },
  sources: {
    editorial: {
      sourceId: editorial.sourceId,
      sourceUrl: editorial.sourceUrl,
      modified: editorial.modified,
      retrievedAt: editorial.retrievedAt,
      credit: editorial.credit,
    },
    renderedMoons: {
      count: renderedMoonCount,
      retrievedAt: moonCatalog.retrievedAt,
      sources: moonCatalog.sources,
    },
  },
});

await writeFile(
  output,
  `// Generated by tools/prepare-panel-content.mjs from declared local sources.\nexport const PREPARED_SATURN_PANEL = Object.freeze(${JSON.stringify(PREPARED_SATURN_PANEL)});\n`,
);
console.log(`Prepared Saturn panel content -> ${output.pathname}`);

function sectionText(heading) {
  const section = editorial.sections.find((entry) => entry.heading === heading);
  if (!section) throw new Error(`Saturn editorial snapshot is missing ${heading}.`);
  return section.paragraphs.join(" ");
}

function capture(text, pattern) {
  const match = text.match(pattern);
  if (!match) throw new Error(`Saturn editorial fact no longer matches ${pattern}.`);
  return match[1];
}

function assertIncludes(text, value) {
  if (!text.includes(value)) throw new Error(`Saturn editorial fact is missing ${value}.`);
}

function deepFreeze(value) {
  for (const child of Object.values(value)) {
    if (child && typeof child === "object") deepFreeze(child);
  }
  return Object.freeze(value);
}
