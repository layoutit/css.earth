#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { validatePlanetInformationSnapshot } from
  "../../../../tools/planet-information-sources.mjs";
import { validateMoonSourceGroup } from "./source-manifest.mjs";

await validateMoonSourceGroup("panel");
const [editorial, physical] = await Promise.all([
  readFile(resolve(import.meta.dirname, "../../../../data/planets/moon.json"),
    "utf8").then(JSON.parse),
  readFile(resolve(import.meta.dirname, "../source/orbit/moon.json"),
    "utf8").then(JSON.parse),
]);
validatePlanetInformationSnapshot(editorial);
if (physical.schema !== "cssearth-earth-moon-source@1") {
  throw new TypeError("Moon physical facts are incompatible.");
}
const prepared = Object.freeze({
  schema: "cssmoon-prepared-panel@1",
  sourceId: editorial.sourceId,
  sourceUrl: editorial.sourceUrl,
  modified: editorial.modified,
  retrievedAt: editorial.retrievedAt,
  introduction: editorial.introduction,
  facts: Object.freeze([
    Object.freeze({ label: "Radius", value: `${physical.meanRadiusKm.toLocaleString("en-US")} km` }),
    Object.freeze({ label: "Earth distance", value: `${physical.meanOrbitRadiusKm.toLocaleString("en-US")} km` }),
    Object.freeze({ label: "Orbit", value: `${physical.orbitalPeriodDays} days` }),
    Object.freeze({ label: "Density", value: `${physical.meanDensityGPerCm3} g/cm³` }),
  ]),
  moreFacts: Object.freeze([
    Object.freeze({ label: "NAIF id", value: String(physical.naifId) }),
    Object.freeze({ label: "Inclination", value: `${physical.inclinationDegrees}°` }),
    Object.freeze({ label: "Eccentricity", value: String(physical.eccentricity) }),
    Object.freeze({ label: "Rotation", value: "synchronous" }),
  ]),
});
await writeFile(
  resolve(import.meta.dirname, "../site/preparedPanel.mjs"),
  "// Generated by tools/prepare-panel-content.mjs.\n" +
    `export const PREPARED_MOON_PANEL = Object.freeze(${JSON.stringify(prepared)});\n`,
);
