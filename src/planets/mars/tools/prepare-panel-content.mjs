import { writeFile } from "node:fs/promises";

import editorial from "../../../../data/planets/mars.json" with { type: "json" };
import { PREPARED_MARS_MOONS } from "../runtime/preparedMoons.mjs";

const output = new URL("../site/preparedPanel.mjs", import.meta.url);
const size = sectionText("Size and Distance");
const orbit = sectionText("Orbit and Rotation");
const moons = sectionText("Moons");

const distance = capture(size, /\(228 million kilometers\)/u, "228 million km");
const radius = Number(capture(size, /\((3,390) kilometers\)/u).replace(",", ""));
const year = capture(orbit, /same as (687 Earth days)/u);
const day = `${capture(orbit, /every (24\.6) hours/u)} hours`;
assertIncludes(moons, "Mars has two small moons");
for (const required of [
  "dusty, cold, desert world",
  "very thin atmosphere",
  "polar ice caps",
  "extinct volcanoes",
]) {
  assertIncludes(editorial.introduction, required);
}

export const PREPARED_MARS_PANEL = deepFreeze({
  schema: "cssearth-prepared-panel@1",
  planetId: "mars",
  introduction: "Mars is a cold, dusty desert world with a thin atmosphere, polar ice caps, extinct volcanoes, deep canyons, seasons, and weather.",
  facts: [
    { label: "Distance", value: distance },
    { label: "Diameter", value: `${(radius * 2).toLocaleString("en-US")} km` },
    { label: "Year", value: year },
    { label: "Day", value: day },
    { label: "Moons", value: String(PREPARED_MARS_MOONS.moons.length) },
  ],
  sources: {
    editorial: {
      sourceId: editorial.sourceId,
      sourceUrl: editorial.sourceUrl,
      modified: editorial.modified,
      retrievedAt: editorial.retrievedAt,
      credit: editorial.credit,
    },
    renderedMoons: {
      count: PREPARED_MARS_MOONS.moons.length,
      physicalParameters: PREPARED_MARS_MOONS.sourceAuthority.physicalParameters,
      meanElements: PREPARED_MARS_MOONS.sourceAuthority.meanElements,
    },
  },
});

await writeFile(
  output,
  `// Generated by tools/prepare-panel-content.mjs from declared local sources.\nexport const PREPARED_MARS_PANEL = Object.freeze(${JSON.stringify(PREPARED_MARS_PANEL)});\n`,
);
console.log(`Prepared Mars panel content -> ${output.pathname}`);

function sectionText(heading) {
  const section = editorial.sections.find((entry) => entry.heading === heading);
  if (!section) throw new Error(`Mars editorial snapshot is missing ${heading}.`);
  return section.paragraphs.join(" ");
}

function capture(text, pattern, replacement) {
  const match = text.match(pattern);
  if (!match) throw new Error(`Mars editorial fact no longer matches ${pattern}.`);
  return replacement ?? match[1];
}

function assertIncludes(text, value) {
  if (!text.includes(value)) throw new Error(`Mars editorial fact is missing ${value}.`);
}

function deepFreeze(value) {
  for (const child of Object.values(value)) {
    if (child && typeof child === "object") deepFreeze(child);
  }
  return Object.freeze(value);
}
