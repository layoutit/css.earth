#!/usr/bin/env node

import { writeFile } from "node:fs/promises";

import editorial from "../../../../data/planets/venus.json" with { type: "json" };

const output = new URL("../site/preparedPanel.mjs", import.meta.url);
const size = sectionText("Size and Distance");
const orbit = sectionText("Orbit and Rotation");
const moons = sectionText("Moons");
const rings = sectionText("Rings");
const surface = sectionText("Surface");
const atmosphere = sectionText("Atmosphere");

assertIncludes(editorial.introduction, "second planet from the Sun");
assertIncludes(editorial.introduction, "hottest planet");
assertIncludes(moons, "doesn't have a moon");
assertIncludes(rings, "no rings");

const panel = deepFreeze({
  schema: "cssearth-prepared-panel@1",
  planetId: "venus",
  introduction: "Venus is the second planet from the Sun and our closest planetary neighbor. It is the hottest planet in the solar system, often called Earth's twin.",
  facts: [
    { label: "Distance", value: `${capture(size, /\((108 million) kilometers\)/u)} km` },
    { label: "Diameter", value: `${capture(size, /\((12,104) kilometers\)/u)} km` },
    { label: "Year", value: `${capture(orbit, /takes only (225) Earth days/u)} Earth days` },
    { label: "Day", value: `${capture(orbit, /day.*?would be (243) Earth days long/u)} Earth days` },
  ],
  moreFacts: [
    { label: "Light time", value: `${wordNumber(capture(size, /takes about (six) minutes/u))} min` },
    { label: "Tilt", value: `${wordNumber(capture(orbit, /tilt is only (three) degrees/u))}°` },
    { label: "Moons", value: "0", title: "Venus has no natural moons." },
    { label: "Rings", value: "0", title: "Venus has no rings." },
    { label: "Surface", value: `${capture(surface, /\((467) Celsius\)/u)}°C` },
    { label: "Pressure", value: `${capture(atmosphere, /crushing (93) times/u)}× Earth` },
  ],
  sources: {
    editorial: {
      sourceId: editorial.sourceId,
      sourceUrl: editorial.sourceUrl,
      modified: editorial.modified,
      retrievedAt: editorial.retrievedAt,
      credit: editorial.credit,
    },
  },
});

await writeFile(
  output,
  "// Generated by tools/prepare-panel-content.mjs from the declared NASA snapshot.\n" +
    `export const PREPARED_VENUS_PANEL = Object.freeze(${JSON.stringify(panel)});\n`,
);
console.log(`Prepared Venus panel content -> ${output.pathname}`);

function sectionText(heading) {
  const section = editorial.sections.find((entry) => entry.heading === heading);
  if (!section) throw new Error(`Venus editorial snapshot is missing ${heading}.`);
  return section.paragraphs.join(" ");
}

function capture(text, pattern) {
  const match = text.match(pattern);
  if (!match) throw new Error(`Venus editorial fact no longer matches ${pattern}.`);
  return match[1];
}

function wordNumber(value) {
  const values = Object.freeze({ three: 3, six: 6 });
  const number = values[value];
  if (!Number.isSafeInteger(number)) {
    throw new Error(`Unsupported Venus source number: ${value}.`);
  }
  return number;
}

function assertIncludes(text, value) {
  if (!text.includes(value)) throw new Error(`Venus editorial fact is missing ${value}.`);
}

function deepFreeze(value) {
  for (const child of Object.values(value)) {
    if (child && typeof child === "object") deepFreeze(child);
  }
  return Object.freeze(value);
}
