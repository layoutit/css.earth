#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { prepareSolarSystemMarkerStrip } from "../../../../tools/objects/solar-system-markers.mjs";
import solarSystemSource from "../source/presentation/solar-system.json" with { type: "json" };
import { VENUS_PUBLIC_ROOT } from "./preparation-paths.mjs";
import { validateVenusSourceGroup } from "./source-manifest.mjs";

await validateVenusSourceGroup("system-markers");
const { plan, assets } = await prepareSolarSystemMarkerStrip(solarSystemSource.markerStrip);
await mkdir(VENUS_PUBLIC_ROOT, { recursive: true });
for (const asset of assets) await writeFile(resolve(VENUS_PUBLIC_ROOT, asset.url.split("/").at(-1)), asset.bytes);
await writeFile(new URL("../runtime/preparedSystemMarkers.mjs", import.meta.url),
  "// Generated by src/planets/venus/tools/prepare-system-markers.mjs. Do not edit.\n" +
  `export const PREPARED_VENUS_SYSTEM_MARKERS = Object.freeze(${JSON.stringify(plan)});\n`);
console.log(`Prepared ${plan.count} Venus system marker tiles.`);
