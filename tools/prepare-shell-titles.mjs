#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { sha256 } from "../src/platform/prepared-title.mjs";
import { SHELL_TITLE_SOURCES } from "../site/source/titles/manifest.mjs";

const SAFE_FILE = /^title-[a-z0-9-]+\.svg$/u;
const SAFE_KEY = /^[a-z][A-Za-z0-9]*$/u;
const SVG_ROOT = /<svg\b[^>]*\bviewBox="0 0 ([0-9.]+) ([0-9.]+)"[^>]*\bwidth="([0-9.]+)"[^>]*\bheight="([0-9.]+)"[^>]*>/u;
const SVG_METADATA = /<metadata>([^<]+)<\/metadata>/u;

export async function prepareShellTitles({
  sourceRoot = resolve(import.meta.dirname, "../site/source/titles"),
  publicRoot = resolve(import.meta.dirname, "../public/shell"),
  moduleOutput = resolve(import.meta.dirname, "../site/prepared-shell-titles.mjs"),
} = {}) {
  validateManifest();
  await mkdir(publicRoot, { recursive: true });
  const prepared = {};
  for (const descriptor of SHELL_TITLE_SOURCES.titles) {
    const sourcePath = resolve(sourceRoot, descriptor.file);
    const bytes = await readFile(sourcePath);
    const svg = bytes.toString("utf8");
    const root = svg.match(SVG_ROOT);
    const metadataMatch = svg.match(SVG_METADATA);
    if (!root || !metadataMatch) {
      throw new Error(`Shell title source is malformed: ${descriptor.file}.`);
    }
    const metadata = JSON.parse(metadataMatch[1]);
    if (metadata.source !== SHELL_TITLE_SOURCES.font.source ||
        metadata.text !== descriptor.vectorText ||
        metadata.weight !== SHELL_TITLE_SOURCES.recipe.weight ||
        metadata.fontSize !== SHELL_TITLE_SOURCES.recipe.fontSize ||
        metadata.letterSpacing !== SHELL_TITLE_SOURCES.recipe.letterSpacing) {
      throw new Error(`Shell title source identity drifted: ${descriptor.file}.`);
    }
    const [, viewBoxWidth, viewBoxHeight, width, height] = root;
    if (viewBoxWidth !== width || viewBoxHeight !== height ||
        Number(height) !== SHELL_TITLE_SOURCES.recipe.viewBoxHeight) {
      throw new Error(`Shell title dimensions drifted: ${descriptor.file}.`);
    }
    await writeFile(resolve(publicRoot, descriptor.file), bytes);
    prepared[descriptor.key] = Object.freeze({
      label: descriptor.label,
      src: `/shell/${descriptor.file}`,
      width: Number(width),
      height: Number(height),
      source: SHELL_TITLE_SOURCES.font.source,
      sourceUrl: SHELL_TITLE_SOURCES.font.sourceUrl,
      sourceSha256: SHELL_TITLE_SOURCES.font.sourceSha256,
      fontSize: SHELL_TITLE_SOURCES.recipe.fontSize,
      inputSha256: sha256(bytes),
      generator: "tools/prepare-shell-titles.mjs",
    });
  }
  const moduleSource = [
    "// Generated from site/source/titles. Do not edit this file directly.",
    `export const PREPARED_SHELL_TITLES = deepFreeze(${JSON.stringify(prepared)});`,
    "",
    "function deepFreeze(value) {",
    "  for (const child of Object.values(value)) Object.freeze(child);",
    "  return Object.freeze(value);",
    "}",
    "",
  ].join("\n");
  await mkdir(dirname(moduleOutput), { recursive: true });
  await writeFile(moduleOutput, moduleSource);
  return Object.freeze({ prepared: Object.freeze(prepared), moduleSource });
}

function validateManifest() {
  if (SHELL_TITLE_SOURCES.schema !== "cssearth-shell-title-sources@1" ||
      !/^[0-9a-f]{64}$/u.test(SHELL_TITLE_SOURCES.font.sourceSha256) ||
      SHELL_TITLE_SOURCES.recipe.fontSize !== 17 ||
      SHELL_TITLE_SOURCES.recipe.viewBoxHeight !== 23) {
    throw new TypeError("Shell title source manifest is incompatible.");
  }
  const keys = new Set();
  const files = new Set();
  for (const descriptor of SHELL_TITLE_SOURCES.titles) {
    if (!SAFE_KEY.test(descriptor.key) || !SAFE_FILE.test(descriptor.file) ||
        !descriptor.label || !descriptor.vectorText || keys.has(descriptor.key) ||
        files.has(descriptor.file)) {
      throw new TypeError("Shell title source descriptor is invalid.");
    }
    keys.add(descriptor.key);
    files.add(descriptor.file);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await prepareShellTitles();
}
