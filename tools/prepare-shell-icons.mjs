#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { sha256 } from "../src/platform/prepared-title.mjs";
import { SHELL_ICON_SOURCES } from "../site/source/icons/manifest.mjs";

const SAFE_SOURCE_FILE = /^symbol-[a-z0-9-]+\.svg$/u;
const SAFE_OUTPUT_FILE = /^icon-[a-z0-9-]+\.svg$/u;
const SAFE_KEY = /^[a-z][A-Za-z0-9]*$/u;
const SVG_ROOT = /<svg\b[^>]*\bwidth="([0-9.]+)"[^>]*\bheight="([0-9.]+)"[^>]*\bviewBox="0 0 ([0-9.]+) ([0-9.]+)"[^>]*>/u;

export async function prepareShellIcons({
  sourceRoot = resolve(import.meta.dirname, "../site/source/icons"),
  publicRoot = resolve(import.meta.dirname, "../public/shell"),
  moduleOutput = resolve(import.meta.dirname, "../site/prepared-shell-icons.mjs"),
} = {}) {
  validateManifest();
  await mkdir(publicRoot, { recursive: true });
  const prepared = {};
  for (const descriptor of SHELL_ICON_SOURCES.icons) {
    const sourcePath = resolve(sourceRoot, descriptor.file);
    const sourceBytes = await readFile(sourcePath);
    if (sha256(sourceBytes) !== descriptor.sourceSha256) {
      throw new Error(`Shell icon source identity drifted: ${descriptor.file}.`);
    }
    const sourceSvg = sourceBytes.toString("utf8");
    const root = sourceSvg.match(SVG_ROOT);
    if (!root || Number(root[1]) !== SHELL_ICON_SOURCES.recipe.width ||
        Number(root[2]) !== SHELL_ICON_SOURCES.recipe.height ||
        Number(root[3]) <= 0 || Number(root[4]) <= 0 ||
        !sourceSvg.includes(SHELL_ICON_SOURCES.recipe.fill)) {
      throw new Error(`Shell icon source is malformed: ${descriptor.file}.`);
    }
    await writeFile(resolve(publicRoot, descriptor.outputFile), sourceBytes);
    prepared[descriptor.key] = Object.freeze({
      label: descriptor.label,
      glyph: descriptor.glyph,
      src: `/shell/${descriptor.outputFile}`,
      width: SHELL_ICON_SOURCES.recipe.width,
      height: SHELL_ICON_SOURCES.recipe.height,
      family: SHELL_ICON_SOURCES.family,
      sourceName: descriptor.sourceName,
      sourceUrl: descriptor.sourceUrl,
      sourceSha256: descriptor.sourceSha256,
      preparedSha256: descriptor.sourceSha256,
      license: descriptor.license,
      licenseUrl: descriptor.licenseUrl,
      attribution: descriptor.author,
      adaptation: `Wikimedia Commons ${descriptor.glyph} symbol normalized to a 20px outer SVG box.`,
      generator: "tools/prepare-shell-icons.mjs",
    });
  }
  const moduleSource = [
    "// Generated from site/source/icons. Do not edit this file directly.",
    `export const PREPARED_SHELL_ICONS = deepFreeze(${JSON.stringify(prepared)});`,
    "",
    "function deepFreeze(value) {",
    "  for (const child of Object.values(value)) Object.freeze(child);",
    "  return Object.freeze(value);",
    "}",
    "",
  ].join("\n");
  await mkdir(dirname(moduleOutput), { recursive: true });
  await writeFile(moduleOutput, moduleSource);
  return Object.freeze({ prepared: Object.freeze(prepared), moduleSource });
}

function validateManifest() {
  if (SHELL_ICON_SOURCES.schema !== "cssearth-shell-icon-sources@1" ||
      SHELL_ICON_SOURCES.recipe.width !== 20 ||
      SHELL_ICON_SOURCES.recipe.height !== 20 ||
      SHELL_ICON_SOURCES.recipe.fill !== "#aaa") {
    throw new TypeError("Shell icon source manifest is incompatible.");
  }
  const keys = new Set();
  const sourceFiles = new Set();
  const outputFiles = new Set();
  for (const descriptor of SHELL_ICON_SOURCES.icons) {
    if (!SAFE_KEY.test(descriptor.key) ||
        !SAFE_SOURCE_FILE.test(descriptor.file) ||
        !SAFE_OUTPUT_FILE.test(descriptor.outputFile) ||
        !descriptor.label || !descriptor.glyph || !descriptor.sourceName ||
        !descriptor.author || !descriptor.license || !descriptor.licenseUrl ||
        !/^https:\/\/commons\.wikimedia\.org\/wiki\/File:/u.test(descriptor.sourceUrl) ||
        !/^[0-9a-f]{64}$/u.test(descriptor.sourceSha256) ||
        keys.has(descriptor.key) || sourceFiles.has(descriptor.file) ||
        outputFiles.has(descriptor.outputFile)) {
      throw new TypeError("Shell icon source descriptor is invalid.");
    }
    keys.add(descriptor.key);
    sourceFiles.add(descriptor.file);
    outputFiles.add(descriptor.outputFile);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await prepareShellIcons();
}
