#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import * as fontkit from "fontkit";

import { OBJECTS } from "../site/objects.mjs";
import { PLANET_TITLE_RECIPE } from
  "../src/platform/planet-title-recipe.mjs";
import { sha256 } from "../src/platform/prepared-title.mjs";

const projectRoot = resolve(import.meta.dirname, "..");

export async function preparePlanetTitleSources({
  fontPath = resolve(projectRoot, PLANET_TITLE_RECIPE.checkedFontPath),
  writeSource = async (planet, moduleSource) => writeFile(
    resolve(
      projectRoot,
      `src/planets/${planet.id}/source/presentation/title-mark.mjs`,
    ),
    moduleSource,
  ),
} = {}) {
  const fontBytes = await readFile(fontPath);
  if (sha256(fontBytes) !== PLANET_TITLE_RECIPE.sourceSha256) {
    throw new Error("The checked Inter title font does not match its pinned hash.");
  }

  const baseFont = fontkit.openSync(fontPath);
  const font = baseFont.getVariation({
    wght: PLANET_TITLE_RECIPE.weight,
    opsz: PLANET_TITLE_RECIPE.opticalSize,
  });
  const prepared = {};
  for (const planet of OBJECTS) {
    const source = createPlanetTitleSource(planet.name, font);
    const exportName = `${planet.id.toUpperCase()}_TITLE_SOURCE`;
    const moduleSource = serializePlanetTitleSource(exportName, source);
    await writeSource(planet, moduleSource);
    prepared[planet.id] = Object.freeze({ source, moduleSource });
  }
  return Object.freeze(prepared);
}

export function createPlanetTitleSource(label, font) {
  if (!font || typeof font.layout !== "function") {
    throw new TypeError("Planet title generation requires a loaded font.");
  }
  if (typeof label !== "string" || !/^[A-Za-z]+$/u.test(label)) {
    throw new TypeError("Planet title label is invalid.");
  }

  const scale = PLANET_TITLE_RECIPE.fontSize / font.unitsPerEm;
  const run = font.layout(label);
  const paths = [];
  let penX = 0;
  let penY = 0;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const [index, glyph] of run.glyphs.entries()) {
    const position = run.positions[index];
    const path = glyph.path
      .scale(scale, -scale)
      .translate(
        penX + position.xOffset * scale,
        PLANET_TITLE_RECIPE.baseline - penY - position.yOffset * scale,
      );
    const box = path.bbox;
    minX = Math.min(minX, box.minX);
    minY = Math.min(minY, box.minY);
    maxX = Math.max(maxX, box.maxX);
    maxY = Math.max(maxY, box.maxY);
    paths.push(path);
    penX += position.xAdvance * scale;
    penY += position.yAdvance * scale;
    if (index < run.glyphs.length - 1) {
      penX += PLANET_TITLE_RECIPE.letterSpacing;
    }
  }

  if (!Number.isFinite(minX) || minY < 0 ||
      maxY > PLANET_TITLE_RECIPE.viewBoxHeight) {
    throw new Error(`Planet title ${label} exceeds the shared title line box.`);
  }

  const width = stableNumber(maxX - minX);
  const path = paths
    .map((glyphPath) => glyphPath.translate(-minX, 0).toSVG())
    .join("");
  return Object.freeze({
    label,
    viewBox: `0 0 ${width} ${PLANET_TITLE_RECIPE.viewBoxHeight}`,
    width,
    height: PLANET_TITLE_RECIPE.viewBoxHeight,
    path,
    source: PLANET_TITLE_RECIPE.source,
    sourceUrl: PLANET_TITLE_RECIPE.sourceUrl,
    sourceSha256: PLANET_TITLE_RECIPE.sourceSha256,
    weight: PLANET_TITLE_RECIPE.weight,
    opticalSize: PLANET_TITLE_RECIPE.opticalSize,
    fontSize: PLANET_TITLE_RECIPE.fontSize,
    letterSpacing: PLANET_TITLE_RECIPE.letterSpacing,
    baseline: PLANET_TITLE_RECIPE.baseline,
    xOrigin: PLANET_TITLE_RECIPE.xOrigin,
    sourceGenerator: PLANET_TITLE_RECIPE.sourceGenerator,
  });
}

export function serializePlanetTitleSource(exportName, source) {
  if (!/^[A-Z][A-Z0-9_]*$/u.test(exportName ?? "")) {
    throw new TypeError("Planet title source export name is invalid.");
  }
  return [
    "// Generated from the pinned Inter font. Do not edit this file directly.",
    `export const ${exportName} = Object.freeze(${JSON.stringify(source)});`,
    "",
  ].join("\n");
}

function stableNumber(value) {
  return Number(value.toFixed(4));
}

if (process.argv[1] &&
    import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await preparePlanetTitleSources();
}
