import { updateObjectJsonForPresentation } from './prepare-object-json.mjs';
import { prepareMaterialTracks } from "./prepare-materials.mjs";
import { writeFile } from "node:fs/promises";
import { requirePreparedPresentation } from "../src/platform/prepared-presentation-contract.mjs";
import { requirePreparedResourceCatalog } from "./object-runtime-contract.mjs";

function preparedPresentation(plan, controls) {
  plan = { ...plan, materials: prepareMaterialTracks(plan), variants: plan.variants.map(variant => ({ ...variant,
    materials: variant.materials.map(material => ({ ...material, mode: material.mode === "default-pose" ? "frames" : material.mode })) })) };
  requirePreparedPresentation(plan, { controls });
  requirePreparedResourceCatalog(plan.assets);
  return plan;
}
export function serializePreparedPresentation(plan, controls) {
  plan = preparedPresentation(plan, controls);
  return `// Generated by prepare-presentation.mjs. Do not edit.\nexport const PREPARED_PRESENTATION = Object.freeze(${JSON.stringify(plan)});\n`;
}
export async function writePreparedPresentation(path, plan, controls) {
  const prepared = preparedPresentation(plan, controls);
  await writeFile(path, serializePreparedPresentation(plan, controls));
  await updateObjectJsonForPresentation(path, prepared, controls);
}
