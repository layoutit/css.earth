import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { parseAst } from 'vite';

const require = createRequire(import.meta.url);
const version = JSON.parse(await readFile(require.resolve('@cesium/engine/package.json'), 'utf8')).version;
if (version !== '26.3.0') throw new Error('Review the minimap excerpts before updating Cesium.');

// Copy only the upstream methods computeViewRectangle uses. The complete
// classes also import image loading and renderer feature detection.
const excerpts = [
  { name: 'BoundingSphere', imports: ['Cartesian3', 'Check', 'Intersect'],
    methods: ['constructor', 'static:intersectPlane', 'intersectPlane'] },
  { name: 'Rectangle', imports: ['Check', 'defined', 'CesiumMath'],
    methods: ['constructor', 'width', 'height', 'static:computeWidth', 'static:computeHeight', 'static:fromCartographicArray'],
    constant: 'Rectangle.MAX_VALUE' },
];

export async function cesiumMinimapExcerpts() {
  const output = new Map();
  for (const { name, imports, methods, constant } of excerpts) {
    const source = await readFile(require.resolve(`@cesium/engine/Source/Core/${name}.js`), 'utf8');
    const ast = parseAst(source);
    const declaration = ast.body.find(node => node.type === 'ClassDeclaration' && node.id.name === name);
    const selected = methods.map(key => {
      const method = declaration.body.body.find(node => `${node.static ? 'static:' : ''}${node.key.name}` === key);
      if (!method) throw new Error(`Missing Cesium method ${name}.${key}`);
      return source.slice(method.start, method.end);
    });
    const dependencies = imports.map(name => {
      const entry = ast.body.find(node => node.type === 'ImportDeclaration' && node.specifiers.some(specifier => specifier.local.name === name));
      if (!entry) throw new Error(`Missing Cesium import ${name}`);
      return `import ${name} from ${JSON.stringify(`@cesium/engine/Source/Core/${entry.source.value.slice(2)}`)};`;
    });
    let tail = '';
    if (constant) {
      const statement = ast.body.find(node => node.type === 'ExpressionStatement' &&
        node.expression.type === 'AssignmentExpression' && source.slice(node.expression.left.start, node.expression.left.end) === constant);
      if (!statement) throw new Error(`Missing Cesium constant ${constant}`);
      tail = `${source.slice(statement.start, statement.end)}\n`;
    }
    output.set(`cesium-${name}.mjs`, `/**
 * Copyright 2011-2024 CesiumJS Contributors. Apache-2.0; see cesium-LICENSE.md.
 * Generated by tools/prepare-cesium-minimap.mjs from @cesium/engine ${version}.
 * https://github.com/CesiumGS/cesium/blob/1.145/packages/engine/Source/Core/${name}.js
 * Selected methods are copied verbatim; unrelated methods are omitted.
 */
${dependencies.join('\n')}

export default class ${name} {
  ${selected.join('\n\n  ')}
}

${tail}`.trimEnd() + '\n');
  }
  return output;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const [name, source] of await cesiumMinimapExcerpts()) {
    await writeFile(new URL(`../site/vendor/${name}`, import.meta.url), source);
  }
}
